"""Generates the Notepad++ User Defined Language files for Abaqus .msg files.

    python make_udl.py        -> AbaqusMsg_light.xml, AbaqusMsg_dark.xml

The colours are the Okabe-Ito palette used by the Vim plugin (blue = good,
orange = bad), so the meaning reads the same with any type of colour vision.
"""
from xml.sax.saxutils import quoteattr, escape

NAME = "Abaqus msg"
# Notepad++ picks the UDL marked darkModeTheme="yes" for *.msg files while its dark mode is on,
# and the other one otherwise, so both files are installed side by side.
NAMES = {"light": NAME, "dark": NAME + " (dark mode)"}

# Keyword lists. Multi-word keywords are written in double quotes, as UDL requires.
KEYWORDS = {
    # 1: converged / completed
    1: ['"HAVE CONVERGED"', '"HAVE CONVERGED."', '"WITHIN THE TOLERANCES."', '"WITHIN THE TOLERANCE."',
        '"ACCEPTED BASED ON"', '"CORRECTIONS ARE ZERO"', '"RESPONSE WAS LINEAR"', '"RESIDUAL CRITERION"',
        '"STEP TIME COMPLETED"', '"TIME INCREMENT COMPLETED"', '"HAS BEEN COMPLETED"', '"MAY NOW INCREASE"'],
    # 2: failed convergence check
    2: ['"NOT ACHIEVED"', '"NOT YET ACHIEVED"', '"TOO LARGE"', '"OUTSIDE OF CONVERGENCE"',
        '"IS ZERO EVERYWHERE BUT"', '"DISTORTING EXCESSIVELY."'],
    # 3: cutback / divergence / abort
    3: ['"APPEARS TO BE DIVERGING."', '"JUDGED UNLIKELY."', '"TOO MANY"', '"CUT BACK"', '"WILL BE REDUCED"',
        '"LESS THAN THE MINIMUM"', '"NOT BEEN COMPLETED"'],
    # 4: attempt number on the INCREMENT line
    4: ['"ATTEMPT NUMBER"'],
    # 5: severe discontinuity (contact) iterations
    5: ['"SEVERE DISCONTINUITY"', '"SEVERE DISCONTINUITIES"', '"POINTS CHANGED"'],
    # 6: equilibrium iterations
    6: ['"EQUILIBRIUM ITERATION"'],
    # 7: convergence-check labels
    7: ['LARGEST', 'CORRESPONDING', 'AVERAGE', '"TIME AVG."', 'MAX.', 'ESTIMATE'],
    # 8: locations (dimmed so the node numbers stand out)
    8: ['NODE', 'DOF', '"CONTACT PAIR"', 'INSTANCE:'],
}

# Folding: the header opens at "Abaqus", every "INCREMENT n STARTS." line starts a
# new sibling fold (middle keyword), "ANALYSIS SUMMARY:" closes.
FOLD_OPEN, FOLD_MIDDLE, FOLD_CLOSE = "Abaqus", "STARTS.", "SUMMARY:"

# ***MESSAGE: up to end of line; the NOTE delimiter lets keyword list 3 show through
DELIMS = [("***WARNING:", "((EOL))"), ("***ERROR:", "((EOL))"), ("***NOTE:", "((EOL))")]
NEST_KW3 = 0x1000          # SCE_USER_MASK_NESTING_KEYWORD3

BOLD, ITALIC, UNDERLINE = 1, 2, 4

PALETTES = {
    "light": dict(bg="FAFAF7", fg="1D1F23", grey="6E737C", blue="0072B2", orange="A66300", verm="C24E00",
                  warn="7A4A00", green="007A5E", purple="A2457A"),
    "dark":  dict(bg="1B1D22", fg="E4E6EA", grey="A8AEB8", blue="56B4E9", orange="E69F00", verm="FF8C50",
                  warn="F0E442", green="3CC79A", purple="E39AC6"),
}


def styles(p):
    s = {  # name: (colour key, font style, nesting)
        "DEFAULT": ("fg", 0, 0),
        "COMMENTS": ("grey", ITALIC, 0),
        "LINE COMMENTS": ("grey", ITALIC, 0),
        "NUMBERS": ("purple", 0, 0),
        "KEYWORDS1": ("blue", 0, 0),
        "KEYWORDS2": ("orange", 0, 0),
        "KEYWORDS3": ("verm", BOLD | UNDERLINE, 0),
        "KEYWORDS4": ("verm", BOLD, 0),
        "KEYWORDS5": ("purple", BOLD, 0),
        "KEYWORDS6": ("green", BOLD, 0),
        "KEYWORDS7": ("fg", BOLD, 0),
        "KEYWORDS8": ("grey", 0, 0),
        "OPERATORS": ("fg", 0, 0),
        "FOLDER IN CODE1": ("fg", BOLD | UNDERLINE, 0),
        "FOLDER IN CODE2": ("fg", 0, 0),
        "FOLDER IN COMMENT": ("grey", 0, 0),
        "DELIMITERS1": ("warn", 0, 0),
        "DELIMITERS2": ("verm", BOLD, 0),
        "DELIMITERS3": ("grey", ITALIC, NEST_KW3),
    }
    for i in range(4, 9):
        s[f"DELIMITERS{i}"] = ("fg", 0, 0)
    out = []
    for name, (col, font, nest) in s.items():
        # colorStyle 1 = foreground only: every style, DEFAULT included, keeps the background of the
        # Notepad++ theme, so text never sits in boxes of a different colour.
        out.append(f'            <WordsStyle name={quoteattr(name)} fgColor="{p[col]}" bgColor="{p["bg"]}" '
                   f'colorStyle="1" fontName="" fontStyle="{font}" nesting="{nest}" />')
    return "\n".join(out)


def delimiters():
    fields = []
    for i in range(8):
        o, c = DELIMS[i] if i < len(DELIMS) else ("", "")
        fields += [f"{3 * i:02d}{o}", f"{3 * i + 1:02d}", f"{3 * i + 2:02d}{c}"]
    return " ".join(fields)


def udl(palette):
    p = PALETTES[palette]
    dm = ' darkModeTheme="yes"' if palette == "dark" else ""
    kw = "\n".join(f'            <Keywords name="Keywords{i}">{escape(" ".join(KEYWORDS[i]))}</Keywords>'
                   for i in range(1, 9))
    return f"""<NotepadPlus>
    <!-- Abaqus/Standard message file (.msg), for Notepad++ {palette} mode. Generated by make_udl.py -->
    <UserLang name="{NAMES[palette]}" ext="msg"{dm} udlVersion="2.1">
        <Settings>
            <Global caseIgnored="no" allowFoldOfComments="no" foldCompact="no" forcePureLC="0" decimalSeparator="0" />
            <Prefix Keywords1="no" Keywords2="no" Keywords3="no" Keywords4="no" Keywords5="no" Keywords6="no" Keywords7="no" Keywords8="no" />
        </Settings>
        <KeywordLists>
            <Keywords name="Comments">00 01 02 03 04</Keywords>
            <Keywords name="Numbers, prefix1"></Keywords>
            <Keywords name="Numbers, prefix2"></Keywords>
            <Keywords name="Numbers, extras1">E e</Keywords>
            <Keywords name="Numbers, extras2">- +</Keywords>
            <Keywords name="Numbers, suffix1"></Keywords>
            <Keywords name="Numbers, suffix2"></Keywords>
            <Keywords name="Numbers, range"></Keywords>
            <Keywords name="Operators1"></Keywords>
            <Keywords name="Operators2"></Keywords>
            <Keywords name="Folders in code1, open">{FOLD_OPEN}</Keywords>
            <Keywords name="Folders in code1, middle">{FOLD_MIDDLE}</Keywords>
            <Keywords name="Folders in code1, close">{FOLD_CLOSE}</Keywords>
            <Keywords name="Folders in code2, open"></Keywords>
            <Keywords name="Folders in code2, middle"></Keywords>
            <Keywords name="Folders in code2, close"></Keywords>
            <Keywords name="Folders in comment, open"></Keywords>
            <Keywords name="Folders in comment, middle"></Keywords>
            <Keywords name="Folders in comment, close"></Keywords>
{kw}
            <Keywords name="Delimiters">{escape(delimiters())}</Keywords>
        </KeywordLists>
        <Styles>
{styles(p)}
        </Styles>
    </UserLang>
</NotepadPlus>
"""


if __name__ == "__main__":
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    for pal in PALETTES:
        path = os.path.join(here, f"AbaqusMsg_{pal}.xml")
        with open(path, "w", encoding="utf-8", newline="\r\n") as fh:
            fh.write(udl(pal))
        print("wrote", path)
